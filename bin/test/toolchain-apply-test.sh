fixture_content_id() {
 local manifest="$1" config="$2" lock="${3:-$LOCK_ORACLE}" name file digest
 for name in contract.txt manifest.tsv config.toml mise.lock; do
  case "$name" in
   contract.txt) file="$CONTRACT_ORACLE" ;;
   manifest.tsv) file="$manifest" ;;
   config.toml) file="$config" ;;
   mise.lock) file="$lock" ;;
  esac
  digest="$(shasum -a 256 "$file" | awk '{print $1}')"
  printf '%s_sha256=%s\n' "$name" "$digest"
 done | shasum -a 256 | awk '{print $1}'
}

# Seal a test-built revision exactly as publication would: identity recomputed
# from every artifact by the test's own digest, receipt rewritten to match,
# artifacts read-only, directory placed at that identity. Nothing here calls
# production code, so only a production predicate can refuse the result.
seal_fixture_revision() {
 local dir="$1" id contract_hash manifest_hash config_hash lock_hash
 cp "$CONTRACT_ORACLE" "$dir/contract.txt"
 id="$(fixture_content_id "$dir/manifest.tsv" "$dir/config.toml" "$dir/mise.lock")"
 contract_hash="$(shasum -a 256 "$dir/contract.txt" | awk '{print $1}')"
 manifest_hash="$(shasum -a 256 "$dir/manifest.tsv" | awk '{print $1}')"
 config_hash="$(shasum -a 256 "$dir/config.toml" | awk '{print $1}')"
 lock_hash="$(shasum -a 256 "$dir/mise.lock" | awk '{print $1}')"
 printf '{"schema_version":"1","content_id":"%s","contract_sha256":"%s","manifest_sha256":"%s","config_sha256":"%s","lock_sha256":"%s","contract":"mise-revision-v1"}\n' \
  "$id" "$contract_hash" "$manifest_hash" "$config_hash" "$lock_hash" >"$dir/receipt.json"
 chmod 0444 "$dir/contract.txt" "$dir/config.toml" "$dir/manifest.tsv" "$dir/mise.lock" "$dir/receipt.json"
 mv "$dir" "$state/revisions/$id"
 chmod 0555 "$state/revisions/$id"
 printf '%s\n' "$id"
}

remove_fixture_revision() {
