#!/usr/bin/env bash
# Public process contract for verified Mise toolchain revisions.

set -euo pipefail

REPO_ROOT="$(CDPATH='' cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
CLI="$REPO_ROOT/bin/dotfiles/toolchain"
TEST_ROOT="$(mktemp -d)"
FIXTURE_REPO="$TEST_ROOT/repo"
HOME_ROOT="$TEST_ROOT/home"
BIN="$TEST_ROOT/bin"
LEDGER="$TEST_ROOT/mise-ledger"
MISE_ENV_LEDGER="$TEST_ROOT/mise-env-ledger"
MISE_CONTEXT_LEDGER="$TEST_ROOT/mise-context-ledger"
MISE_PYTHON_ATTESTATION_LEDGER="$TEST_ROOT/mise-python-attestation-ledger"
ORACLE="$TEST_ROOT/oracle.tsv"
LOCK_ORACLE="$TEST_ROOT/lock.oracle"
LOCK_PRE_ORACLE="$TEST_ROOT/lock.pre.oracle"
LOCK_WITHOUT_BEADS_ORACLE="$TEST_ROOT/lock.without-beads.oracle"
LOCK_STALE_BEADS_ORACLE="$TEST_ROOT/lock.stale-beads.oracle"
NEGATIVE_LOCKS="$TEST_ROOT/negative-locks"
LOCK_OUTPUT_LEDGER="$TEST_ROOT/lock-output-ledger"
CONTRACT_ORACLE="$TEST_ROOT/contract.oracle"
BEADS_LOCK_VERSION='1.3.0'
BEADS_LOCK_ASSET='beads_1.3.0_darwin_arm64.tar.gz'
BEADS_LOCK_URL="https://github.com/gastownhall/beads/releases/download/v$BEADS_LOCK_VERSION/$BEADS_LOCK_ASSET"
BEADS_LOCK_SHA256='7cc77367d0b84c50243a1108bc1f73648699211257d414b917540bf868e6bb85'
assertion_count=0

cleanup() { chmod -R u+w "$TEST_ROOT" 2>/dev/null || true; rm -rf "$TEST_ROOT"; }
trap cleanup EXIT
pass() { assertion_count=$((assertion_count + 1)); printf 'ok %d - %s\n' "$assertion_count" "$1"; }
fail() { printf 'not ok - %s\n' "$1" >&2; exit 1; }
assert_equals() { [[ "$1" == "$2" ]] || fail "$3 (expected [$1], got [$2])"; pass "$3"; }
assert_contains() { [[ "$1" == *"$2"* ]] || fail "$3 (expected [$2] in [$1])"; pass "$3"; }
# Explicit oracle exception: register a known revision ID's exact config path
# to its test-owned oracle column so it keeps verifying while staging answers
# from MISE_TEST_ORACLE_COLUMN. The fake compares that path, never config bytes.
register_oracle_column() { export MISE_TEST_ORACLE_PATH_COLUMNS="$TOOLCHAIN_EXPECTED_STATE/revisions/$1/config.toml|$2"; }
assert_file() { [[ -r "$1" ]] || fail "$2"; pass "$2"; }
assert_not_exists() { [[ ! -e "$1" && ! -L "$1" ]] || fail "$2"; pass "$2"; }
assert_process_gone() {
 local pid="$1" label="$2" state=''
 for _ in $(seq 1 100); do
  if ! kill -0 "$pid" 2>/dev/null; then pass "$label"; return; fi
  state="$(ps -o stat= -p "$pid" 2>/dev/null | tr -d ' ')"
  [[ "$state" == Z* ]] && { pass "$label"; return; }
  sleep 0.02
 done
 fail "$label (pid $pid remains live with state $state)"
}
assert_process_group_gone() {
 local pgid="$1" label="$2"
 for _ in $(seq 1 100); do
  if ! kill -0 -- "-$pgid" 2>/dev/null; then pass "$label"; return; fi
  sleep 0.02
 done
 fail "$label (process group $pgid remains live)"
}

# Independent oracle: these literals are not read from the source declaration
# or from any config under test. The fake Mise answers every version probe from
# the column selected by MISE_TEST_ORACLE_COLUMN (default 2), so a test that
# declares another version must also select the column that matches it.
# Columns 2 through 8: Node 26.9.0 through 26.9.6. Column 9: Node 26.9.7
# (sealed control). Column 10: Beads 1.2.2 (verified rollback baseline).
# Column 11: independently wrong npm control for Node 26.9.1.
cat >"$ORACLE" <<'EOF'
node|26.9.0|26.9.1|26.9.2|26.9.3|26.9.4|26.9.5|26.9.6|26.9.7|26.9.0|26.9.1
bun|1.4.0|1.4.0|1.4.0|1.4.0|1.4.0|1.4.0|1.4.0|1.4.0|1.4.0|1.4.0
python|3.11.9|3.11.9|3.11.9|3.11.9|3.11.9|3.11.9|3.11.9|3.11.9|3.11.9|3.11.9
bd|1.3.0|1.3.0|1.3.0|1.3.0|1.3.0|1.3.0|1.3.0|1.3.0|1.2.2|1.3.0
npm|11.19.1|11.19.1|11.19.1|11.19.1|11.19.1|11.19.1|11.19.1|11.19.1|11.19.1|11.19.0
EOF
# Independent oracle: these lock bodies are test-owned TOML in the
# `lockfile_version = 2` shape Mise 2026.9.10 writes. They are never derived
# from the source declaration or from production parsing. Each negative fixture
# perturbs exactly one fact about the Beads record.
write_lock() {
  local path="$1" format="${2-lockfile_version = 2}"
  {
    printf '%s\n' '# @generated - this file is auto-generated by `mise lock` https://mise.jdx.dev/dev-tools/mise-lock.html' ''
    [[ -z "$format" ]] || printf '%s\n' "$format" ''
    cat
  } >"$path"
}
node_lock_entry() {
  printf '%s\n' '[[tools.node]]' 'version = "26.9.0"' 'backend = "core:node"' 'specifiers = ["26.9.0"]' '' \
    '[tools.node."platforms.macos-arm64"]' \
    'checksum = "sha256:6f3de7ed853ee283b4bf24b6e426618f1d357401ce5815db1866eb85eb4b05d9"' \
    'url = "https://nodejs.org/dist/v26.9.0/node-v26.9.0-darwin-arm64.tar.gz"' ''
}
beads_lock_entry() {
  local version="$1" backend="$2" specifiers="$3" checksum="$4" url="$5"
  printf '%s\n' '[[tools."github:gastownhall/beads"]]' "version = \"$version\"" "backend = \"$backend\"" "specifiers = $specifiers" '' \
    '[tools."github:gastownhall/beads"."platforms.macos-arm64"]' "checksum = \"sha256:$checksum\"" "url = \"$url\""
}
official_beads_lock_entry() {
  beads_lock_entry "$BEADS_LOCK_VERSION" 'github:gastownhall/beads' "[\"$BEADS_LOCK_VERSION\"]" "$BEADS_LOCK_SHA256" "$BEADS_LOCK_URL"
}
mkdir -p "$NEGATIVE_LOCKS"
{ node_lock_entry; official_beads_lock_entry; } | write_lock "$LOCK_PRE_ORACLE"
# Install enrichment adds a Node platform and Mise-owned Beads asset metadata.
{
  node_lock_entry
  printf '%s\n' '[tools.node."platforms.macos-x64"]' \
    'checksum = "sha256:06b2e742ed9025dc84adc830243b3f731956eac9c321bccd0ede384209af02a8"' \
    'url = "https://nodejs.org/dist/v26.9.0/node-v26.9.0-darwin-x64.tar.gz"' ''
  official_beads_lock_entry
  printf '%s\n' 'url_api = "https://api.github.com/repos/gastownhall/beads/releases/assets/566378329"' 'provenance = "github-attestations"'
} | write_lock "$LOCK_ORACLE"
node_lock_entry | write_lock "$LOCK_WITHOUT_BEADS_ORACLE"
{
  node_lock_entry
  beads_lock_entry '1.2.2' 'github:gastownhall/beads' '["1.2.2"]' \
    '2aa1245c666419900d2d6993a05049e92c40e0e601d19579cca5b07a7bb8021d' \
    'https://github.com/gastownhall/beads/releases/download/v1.2.2/beads_1.2.2_darwin_arm64.tar.gz'
} | write_lock "$LOCK_STALE_BEADS_ORACLE"
{ node_lock_entry; official_beads_lock_entry | sed '$s/"$//'; } | write_lock "$NEGATIVE_LOCKS/malformed.lock"
# Every Beads fact is intact; the only defect is a tolerated extra field whose
# bare value is not TOML. A lenient reader would accept this lock.
{ node_lock_entry; official_beads_lock_entry; printf '%s\n' 'extra = nope'; } | write_lock "$NEGATIVE_LOCKS/bare-value.lock"
# Shape-valid but semantically impossible date: Python tomllib rejects it, and
# no required Mise lock field is a date or time, so the reader must not accept
# any bare date or time scalar.
{ node_lock_entry; official_beads_lock_entry; printf '%s\n' 'extra = 2026-99-99'; } | write_lock "$NEGATIVE_LOCKS/malformed-date.lock"
{
  node_lock_entry; official_beads_lock_entry
  printf '%s\n' '' '[tools."github:gastownhall/beads"."platforms.macos-arm64"]' "checksum = \"sha256:$BEADS_LOCK_SHA256\"" "url = \"$BEADS_LOCK_URL\""
} | write_lock "$NEGATIVE_LOCKS/duplicate-platform.lock"
{ node_lock_entry; beads_lock_entry "$BEADS_LOCK_VERSION" 'ubi:gastownhall/beads' "[\"$BEADS_LOCK_VERSION\"]" "$BEADS_LOCK_SHA256" "$BEADS_LOCK_URL"; } | write_lock "$NEGATIVE_LOCKS/wrong-backend.lock"
{ node_lock_entry; beads_lock_entry "$BEADS_LOCK_VERSION" 'github:gastownhall/beads' '["1.2.2"]' "$BEADS_LOCK_SHA256" "$BEADS_LOCK_URL"; } | write_lock "$NEGATIVE_LOCKS/wrong-specifier.lock"
{ node_lock_entry; beads_lock_entry "$BEADS_LOCK_VERSION" 'github:gastownhall/beads' "[\"$BEADS_LOCK_VERSION\", \"$BEADS_LOCK_VERSION\"]" "$BEADS_LOCK_SHA256" "$BEADS_LOCK_URL"; } | write_lock "$NEGATIVE_LOCKS/duplicate-specifier.lock"
{ node_lock_entry; beads_lock_entry "$BEADS_LOCK_VERSION" 'github:gastownhall/beads' "\"$BEADS_LOCK_VERSION\"" "$BEADS_LOCK_SHA256" "$BEADS_LOCK_URL"; } | write_lock "$NEGATIVE_LOCKS/string-specifier.lock"
{ node_lock_entry; official_beads_lock_entry | grep -v '^specifiers = '; } | write_lock "$NEGATIVE_LOCKS/missing-specifier.lock"
{ node_lock_entry; beads_lock_entry "$BEADS_LOCK_VERSION" 'github:gastownhall/beads' "[\"$BEADS_LOCK_VERSION\"]" "$BEADS_LOCK_SHA256" "${BEADS_LOCK_URL/darwin_arm64/darwin_amd64}"; } | write_lock "$NEGATIVE_LOCKS/wrong-url.lock"
{ node_lock_entry; beads_lock_entry "$BEADS_LOCK_VERSION" 'github:gastownhall/beads' "[\"$BEADS_LOCK_VERSION\"]" "${BEADS_LOCK_SHA256/7cc7/7cc8}" "$BEADS_LOCK_URL"; } | write_lock "$NEGATIVE_LOCKS/wrong-checksum.lock"
{ node_lock_entry; official_beads_lock_entry; printf '\n'; official_beads_lock_entry; } | write_lock "$NEGATIVE_LOCKS/duplicate-entry.lock"
{ node_lock_entry; official_beads_lock_entry | sed -n '1,4p'; } | write_lock "$NEGATIVE_LOCKS/missing-platform.lock"
{ node_lock_entry; official_beads_lock_entry | sed '1s/^\[\[\(.*\)\]\]$/[\1]/'; } | write_lock "$NEGATIVE_LOCKS/plain-table-entry.lock"
{ node_lock_entry; official_beads_lock_entry; } | write_lock "$NEGATIVE_LOCKS/legacy-format.lock" ''
{ node_lock_entry; official_beads_lock_entry; } | write_lock "$NEGATIVE_LOCKS/future-format.lock" 'lockfile_version = 3'
printf 'mise-revision-v1\n' >"$CONTRACT_ORACLE"

mkdir -p "$HOME_ROOT" "$BIN"
mkdir -p "$FIXTURE_REPO/bin/dotfiles" "$FIXTURE_REPO/config/toolchain" "$FIXTURE_REPO/config/mise"
cp "$CLI" "$FIXTURE_REPO/bin/dotfiles/toolchain"
cp "$REPO_ROOT/config/toolchain/versions.tsv" "$FIXTURE_REPO/config/toolchain/versions.tsv"
cp "$REPO_ROOT/config/mise/source.toml" "$FIXTURE_REPO/config/mise/source.toml"
chmod +x "$FIXTURE_REPO/bin/dotfiles/toolchain"
CLI="$FIXTURE_REPO/bin/dotfiles/toolchain"
cat >"$BIN/mise" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail

python_attestation_policy_is_not_persisted() {
  [[ -n "${MISE_GLOBAL_CONFIG_FILE:-}" ]] || return 1
  ! awk '
    /^\[settings\][[:space:]]*$/ { in_settings=1; next }
    /^\[/ { in_settings=0 }
    in_settings && $0 ~ /^[[:space:]]*python\.github_attestations[[:space:]]*=[[:space:]]*false([[:space:]]*#.*)?$/ { found=1 }
    END { exit !found }
  ' "$MISE_GLOBAL_CONFIG_FILE"
}

printf '%s\n' "$*" >>"$TOOLCHAIN_MISE_LEDGER"
printf '%s|%s|%s\n' "${MISE_DATA_DIR:-unset}" "${MISE_INSTALLS_DIR:-unset}" "${MISE_SHIMS_DIR:-unset}" >>"$TOOLCHAIN_MISE_ENV_LEDGER"
printf '%s|%s\n' "${MISE_PYTHON_GITHUB_ATTESTATIONS:-unset}" "$*" >>"$TOOLCHAIN_MISE_PYTHON_ATTESTATION_LEDGER"
if [[ -n "${MISE_GLOBAL_CONFIG_FILE:-}" ]]; then
  printf '%s|%s|%s|%s|%s\n' "$PWD" "${MISE_CEILING_PATHS:-unset}" "$MISE_GLOBAL_CONFIG_FILE" "${MISE_NODE_VERSION-unset},${MISE_BUN_VERSION-unset},${MISE_PYTHON_VERSION-unset},${MISE_NPM_VERSION-unset},${MISE_CONFIG_FILE-unset},${MISE_CONFIG_DIR-unset},${MISE_DEFAULT_CONFIG_FILENAME-unset}" "$*" >>"$TOOLCHAIN_MISE_CONTEXT_LEDGER"
  if [[ "$PWD" == "$TOOLCHAIN_ADVERSARIAL_PROJECT" ]]; then
    : >"$TOOLCHAIN_PROJECT_SIDE_EFFECT"
  fi
  if [[ -r "$PWD/mise.toml" ]]; then
    : >"$TOOLCHAIN_STATE_SIDE_EFFECT"
    exit 96
  fi
  [[ "$PWD" == "$TOOLCHAIN_EXPECTED_STATE/.mise-operation-"* ]] || exit 96
  [[ "${MISE_CEILING_PATHS:-}" == "$PWD" ]] || exit 96
  [[ "$MISE_GLOBAL_CONFIG_FILE" == "$TOOLCHAIN_EXPECTED_STATE/revisions/"*"/config.toml" ]] || exit 96
  [[ "${MISE_NODE_VERSION+x}${MISE_BUN_VERSION+x}${MISE_PYTHON_VERSION+x}${MISE_NPM_VERSION+x}${MISE_CONFIG_FILE+x}${MISE_CONFIG_DIR+x}${MISE_DEFAULT_CONFIG_FILENAME+x}" == '' ]] || exit 96
  python_attestation_policy_is_not_persisted || exit 71
fi
case "$1" in
 lock)
  [[ "$2" == --global && -n "${MISE_GLOBAL_CONFIG_FILE:-}" ]] || exit 97
  [[ "${MISE_TEST_NOISY:-false}" != true ]] || printf 'fixture lock progress\n'
  post_install_refresh=false
  if [[ -n "${MISE_TEST_POST_INSTALL_LOCK_MARKER:-}" && -r "$MISE_TEST_POST_INSTALL_LOCK_MARKER" ]]; then
    [[ "$(<"$MISE_TEST_POST_INSTALL_LOCK_MARKER")" == "$MISE_GLOBAL_CONFIG_FILE" ]] && post_install_refresh=true
  fi
  if [[ -n "${MISE_TEST_REPLACEMENT_CONFIG:-}" ]]; then
    cp "$MISE_TEST_REPLACEMENT_CONFIG" "$MISE_TEST_CANONICAL_CONFIG"
    cp "$MISE_TEST_REPLACEMENT_MANIFEST" "$MISE_TEST_CANONICAL_MANIFEST"
  fi
  lock_file="$(dirname "$MISE_GLOBAL_CONFIG_FILE")/mise.lock"
  if [[ -n "${MISE_TEST_FORCE_POST_INSTALL_LOCK_FIXTURE:-}" && "$post_install_refresh" == true ]]; then
    cp "$MISE_TEST_FORCE_POST_INSTALL_LOCK_FIXTURE" "$lock_file"
  elif [[ -n "${MISE_TEST_FORCE_LOCK_FIXTURE:-}" && "$post_install_refresh" == false ]]; then
    cp "$MISE_TEST_FORCE_LOCK_FIXTURE" "$lock_file"
  elif [[ ! -e "$lock_file" && ! -L "$lock_file" ]]; then
    if [[ -n "${MISE_TEST_LOCK_MUTATION_MARKER:-}" && -e "$MISE_TEST_LOCK_MUTATION_MARKER" ]]; then
      cp "$TOOLCHAIN_LOCK_WITHOUT_BEADS_ORACLE" "$lock_file"
    else
      cp "$TOOLCHAIN_LOCK_PRE_ORACLE" "$lock_file"
    fi
  fi
  [[ "$post_install_refresh" == false ]] || rm -f "$MISE_TEST_POST_INSTALL_LOCK_MARKER"
  if [[ -n "${MISE_TEST_LOCK_OUTPUT_LEDGER:-}" ]]; then
    shasum -a 256 "$lock_file" | awk '{print $1}' >>"$MISE_TEST_LOCK_OUTPUT_LEDGER"
  fi
  ;;
 install)
  # Locked consumption contract: installation must name exactly `install --locked`
  # so Mise resolves only the pre-resolved lock URLs for this platform.
  [[ $# -eq 2 && "$2" == --locked ]] || exit 98
  [[ "${MISE_TEST_NOISY:-false}" != true ]] || printf 'fixture install progress\n'
  [[ "${MISE_TEST_FAIL_INSTALL:-false}" != true ]] || exit 70
  if [[ -n "${MISE_TEST_GRANDCHILD_PID_FILE:-}" ]]; then
    (while :; do sleep 0.05; done) &
    printf '%s\n' "$!" >"$MISE_TEST_GRANDCHILD_PID_FILE"
  fi
  [[ -z "${MISE_TEST_BLOCK_FILE:-}" ]] || { : >"$MISE_TEST_BLOCK_FILE"; while [[ ! -e "${MISE_TEST_RELEASE_FILE:-}" ]]; do sleep 0.05; done; }
  if [[ "${MISE_TEST_MUTATE_LOCK_ON_INSTALL:-false}" == true ]]; then
    lock_file="$(dirname "$MISE_GLOBAL_CONFIG_FILE")/mise.lock"
    if [[ -n "${MISE_TEST_LOCK_MUTATION_MARKER:-}" && ! -e "$MISE_TEST_LOCK_MUTATION_MARKER" ]]; then
      cp "$TOOLCHAIN_LOCK_ORACLE" "$lock_file"
      if [[ -n "${MISE_TEST_LOCK_OUTPUT_LEDGER:-}" ]]; then
        shasum -a 256 "$lock_file" | awk '{print $1}' >>"$MISE_TEST_LOCK_OUTPUT_LEDGER"
      fi
      : >"$MISE_TEST_LOCK_MUTATION_MARKER"
    fi
  fi
  [[ -z "${MISE_TEST_POST_INSTALL_LOCK_MARKER:-}" ]] || printf '%s\n' "$MISE_GLOBAL_CONFIG_FILE" >"$MISE_TEST_POST_INSTALL_LOCK_MARKER"
  ;;
 which)
  case "$2" in node|bun|python|bd) printf '%s/%s\n' "$TOOLCHAIN_FAKE_RUNTIME" "$2" ;; *) exit 97;; esac
 ;;
 exec)
  # Independent oracle: every answer comes from the test-owned table, never
  # from the config under test. Every probe answers from MISE_TEST_ORACLE_COLUMN
  # unless the test registered the exact config path in the explicit exception
  # map MISE_TEST_ORACLE_PATH_COLUMNS (`config path|column` lines). Only the path
  # is compared; the fake never reads config bytes to choose a version.
  tool="$3"; column="${MISE_TEST_ORACLE_COLUMN:-2}"
  while IFS='|' read -r mapped_path mapped_column; do
    if [[ -n "$mapped_path" && "$mapped_path" == "$MISE_GLOBAL_CONFIG_FILE" ]]; then column="$mapped_column"; fi
  done <<<"${MISE_TEST_ORACLE_PATH_COLUMNS:-}"
  version="$(awk -F '|' -v tool="$tool" -v column="$column" '$1 == tool { print $column; exit }' "$TOOLCHAIN_ORACLE")"
  if [[ "$tool" == node && "${MISE_TEST_VERIFY_FAILURE_MODE:-}" == once && ! -e "${MISE_TEST_VERIFY_FAILURE_MARKER:-}" ]]; then
    : >"$MISE_TEST_VERIFY_FAILURE_MARKER"
    version='0.0.0'
  elif [[ "$tool" == node && "${MISE_TEST_VERIFY_FAILURE_MODE:-}" == always ]]; then
    version='0.0.0'
  fi
  case "$tool" in node) printf 'v%s\n' "$version";; bun) printf '%s\n' "$version";; python) printf 'Python %s\n' "$version";; bd) printf 'bd version %s (fixture)\n' "$version";; *) exit 97;; esac
  ;;
 *) exit 97;;
esac
EOF
chmod +x "$BIN/mise"
cat >"$BIN/ln" <<'EOF'
