fi
if [[ "${MISE_TEST_FAIL_LOCK_LINK:-false}" == true && "$last" == */run-lock ]]; then exit 73; fi
if [[ "${MISE_TEST_BLOCK_LOCK_LINK:-false}" == true && "$last" == */run-lock ]]; then
